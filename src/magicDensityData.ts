const FILES = "ABCDEFGH";

export const squareName = (square: number) =>
  FILES[square % 8] + (8 - Math.floor(square / 8));

/** Board index of a square name like "d5" or "D5". */
export const squareIndex = (name: string) =>
  (8 - Number(name[1])) * 8 + FILES.indexOf(name[0].toUpperCase());
